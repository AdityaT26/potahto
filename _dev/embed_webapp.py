#!/usr/bin/env python3
"""Gzip webapp/index.html into WebApp.h (served by the device at http://<name>.local/).

Run from the sketch folder after editing the web app:
    python _dev/embed_webapp.py
"""
import gzip, os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "webapp", "index.html")
dst = os.path.join(root, "WebApp.h")
raw = open(src, "rb").read()
# inline the PC companion script so the web app can offer it as a download
comp = os.path.join(root, "companion", "potahto_companion.py")
if os.path.exists(comp):
    import json
    raw = raw.replace(b'/*COMPANION*/""', json.dumps(open(comp, encoding="utf-8").read()).replace("</", "<\\/").encode())
gz = gzip.compress(raw, compresslevel=9, mtime=0)
lines = []
for i in range(0, len(gz), 20):
    lines.append("  " + ", ".join("0x%02x" % b for b in gz[i:i + 20]) + ",")
out = (
    "// GENERATED by _dev/embed_webapp.py from webapp/index.html - do not edit.\n"
    "// %d bytes of HTML -> %d bytes gzipped.\n"
    "#pragma once\n#include <Arduino.h>\n\n"
    "static const uint8_t WEBAPP_GZ[] PROGMEM = {\n%s\n};\n"
    "static const size_t WEBAPP_GZ_LEN = sizeof(WEBAPP_GZ);\n"
) % (len(raw), len(gz), "\n".join(lines))
open(dst, "w", newline="\n").write(out)
print("WebApp.h: %d -> %d bytes" % (len(raw), len(gz)))
